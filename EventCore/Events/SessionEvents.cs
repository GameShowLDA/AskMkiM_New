using EventCore.Interfaces;

namespace EventCore.Events
{
  /// <summary>
  /// События пользовательского интерфейса, связанные с управлением сессиями пользователя:
  /// сохранением текущей сессии и открытием ранее сохранённой.
  /// </summary>
  /// <remarks>
  /// Эти события используются для координации действий между слоями приложения при работе с сессиями,
  /// например, при автоматическом сохранении состояния или восстановлении работы после перезапуска программы.
  /// </remarks>
  public static class SessionEvents
  {
    /// <summary>
    /// Событие, генерируемое при сохранении текущей сессии пользователя.
    /// </summary>
    /// <remarks>
    /// Обычно используется для сохранения текущего состояния редакторов, открытых файлов,
    /// активных настроек и контекста выполнения.
    /// </remarks>
    public class SaveSession : IEvent { }

    /// <summary>
    /// Событие, генерируемое при открытии ранее сохранённой сессии пользователя.
    /// </summary>
    /// <remarks>
    /// Обычно инициируется при старте приложения или по запросу пользователя
    /// для восстановления прежнего состояния среды работы.
    /// </remarks>
    public class OpenSession : IEvent { }
  }
}
