namespace DTO.Base.Models.Session
{
  /// <summary>
  /// Модель <see cref="EditorTabSession"/> описывает состояние одной вкладки редактора
  /// в рамках пользовательской сессии. Сохраняет путь к файлу, его имя, содержимое и флаг изменения.
  /// </summary>
  public class EditorTabSession
  {
    /// <summary>
    /// Полный путь к файлу, связанному с данной вкладкой.  
    /// Может быть пустой строкой, если документ ещё не сохранён на диск.
    /// </summary>
    public string FilePath { get; set; } = "";

    /// <summary>
    /// Отображаемое имя вкладки редактора.  
    /// По умолчанию — «Новый», если файл не был сохранён или не имеет имени.
    /// </summary>
    public string FileName { get; set; } = "Новый";

    /// <summary>
    /// Текстовое содержимое открытого файла.  
    /// Используется для восстановления состояния редактора при повторном запуске.
    /// </summary>
    public string TextContent { get; set; } = "";

    /// <summary>
    /// Флаг, указывающий, были ли внесены изменения в содержимое файла с момента последнего сохранения.  
    /// <c>true</c> — документ изменён; <c>false</c> — соответствует сохранённому состоянию.
    /// </summary>
    public bool IsModified { get; set; }
  }
}
