namespace DTO.Base.Models.Session
{
  /// <summary>
  /// Модель <see cref="SessionModel"/> описывает состояние сессии редактора,
  /// включая список открытых вкладок, индекс активной вкладки и момент сохранения сессии.
  /// Используется для восстановления состояния редактора при следующем запуске приложения.
  /// </summary>
  public class SessionModel
  {
    /// <summary>
    /// Коллекция открытых вкладок редактора на момент сохранения сессии.  
    /// Каждая вкладка представлена объектом <see cref="EditorTabSession"/>, содержащим информацию о файле и его состоянии.
    /// </summary>
    public List<EditorTabSession> Tabs { get; set; } = new();

    /// <summary>
    /// Индекс активной вкладки в коллекции <see cref="Tabs"/>.  
    /// Используется для восстановления фокуса на той вкладке, которая была активна при сохранении сессии.
    /// </summary>
    public int ActiveTabIndex { get; set; } = 0;

    /// <summary>
    /// Дата и время сохранения текущей сессии.  
    /// Применяется для отображения времени последнего восстановления и контроля актуальности состояния редактора.
    /// </summary>
    public DateTime SavedAt { get; set; } = DateTime.Now;
  }
}
